import numpy as np
from dotenv import load_dotenv
from langchain_groq import ChatGroq
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

import PyPDF2 as pdf_module


load_dotenv()

reader = pdf_module.PdfReader("sample_chat.pdf")

full_text = ""
for page in reader.pages:
    extracted = page.extract_text()
    if extracted:
        full_text += extracted + "\n"

chunk_size = 500
chunks = [full_text[i:i + chunk_size] for i in range(0, len(full_text), chunk_size)]

vectorizer = TfidfVectorizer()
chunk_embeddings = vectorizer.fit_transform(chunks)

def retrieve_top_chunk(question, text_chunks, embeddings_matrix):
    query_vector = vectorizer.transform([question])
    scores = cosine_similarity(query_vector, embeddings_matrix)[0]
    best_idx = int(np.argmax(scores))
    return text_chunks[best_idx]

user_question = "Who messaged the most and what plans were made for the Goa trip?"
retrieved_context = retrieve_top_chunk(user_question, chunks, chunk_embeddings)

llm = ChatGroq(model_name="openai/gpt-oss-20b", temperature=0.3)

messages = [
    {
        "role": "system",
        "content": "You are a helpful assistant. Answer the user question strictly using the provided context in plain ASCII English only without any unicode spaces, symbols or currency signs."
    },
    {
        "role": "user",
        "content": f"Context:\n{retrieved_context}\n\nQuestion: {user_question}"
    }
]

response = llm.invoke(messages)

print(f"User Question: '{user_question}'\n")
print("Retrieved Context Chunk:")
print("-" * 50)
print(retrieved_context.strip())
print("-" * 50)
print("\nFinal Answer Generated by Groq LLM:")
print(response.content)
